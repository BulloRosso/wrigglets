/*
 * Deterministic "model" used for local development and automated tests.
 *
 * Behaviour for a chat completion request that offers tools:
 *   1. Collect every backticked path that follows the word "write" on a line of the LAST user
 *      message (our prompts follow this convention, see packages/workflows/src/prompts.ts).
 *   2. For each such path that has not been written yet in this turn, call the harness' file
 *      writing tool (detected from the tool schema) with generated Markdown content.
 *   3. When everything is written, answer with a short final text.
 * Requests without tools (e.g. title generation) get a short plain answer.
 */

export interface ChatMessage {
  role: 'system' | 'user' | 'assistant' | 'tool';
  content?: string | Array<{ type: string; text?: string }> | null;
  tool_calls?: Array<{ id: string; type: 'function'; function: { name: string; arguments: string } }>;
  tool_call_id?: string;
}

export interface ToolDef {
  type: 'function';
  function: { name: string; description?: string; parameters?: { properties?: Record<string, unknown> } };
}

export type ScriptedReply =
  | { kind: 'text'; text: string }
  | { kind: 'tool'; name: string; args: Record<string, unknown> };

export const textOf = (c: ChatMessage['content']): string =>
  typeof c === 'string' ? c : Array.isArray(c) ? c.map((p) => p.text ?? '').join('\n') : '';

export function extractWriteTargets(text: string): string[] {
  const out: string[] = [];
  for (const line of text.split('\n')) {
    const m = /\bwrite\b[^`]*`([^`\s]+)`/i.exec(line);
    if (m && /^[\w.\-/]+$/.test(m[1]!) && !m[1]!.startsWith('/') && !m[1]!.includes('..')) out.push(m[1]!);
  }
  return [...new Set(out)];
}

function findWriteTool(tools: ToolDef[]): { name: string; pathKey: string; contentKey: string } | undefined {
  const candidates = tools.filter((t) => /^(write|write_file|create_file)$/i.test(t.function.name));
  for (const t of candidates) {
    const props = Object.keys(t.function.parameters?.properties ?? {});
    const pathKey = props.find((p) => /path/i.test(p));
    const contentKey = props.find((p) => /content/i.test(p));
    if (pathKey && contentKey) return { name: t.function.name, pathKey, contentKey };
  }
  return undefined;
}

function workingDirectory(messages: ChatMessage[]): string {
  for (const m of messages) {
    if (m.role !== 'system') continue;
    const match = /working directory:\s*(\S+)/i.exec(textOf(m.content));
    if (match) return match[1]!.replace(/\/$/, '');
  }
  return process.env.MOCK_DEFAULT_CWD ?? '/home/workspace';
}

function contentFor(path: string, userText: string): string {
  const title = /^Title:\s*(.+)$/m.exec(userText)?.[1] ?? 'Task';
  const task = /^# Task (\S+)/m.exec(userText)?.[1] ?? 'task';
  const now = new Date().toISOString();
  if (path.includes('/plans/')) {
    return [
      `# Plan: ${title}`,
      '',
      '## Goal',
      `Deliver "${title}" as requested.`,
      '',
      '## Inputs',
      '- Files in the workspace relevant to the request',
      '',
      '## Steps',
      '1. Inspect the relevant files.',
      '2. Produce the requested output.',
      '3. Summarize the results.',
      '',
      '## Outputs',
      `- \`reports/${task}.md\``,
      '',
      '## Risks and open questions',
      '- None identified (mock model).',
      '',
      `_Generated by mock-llm at ${now}_`,
      '',
    ].join('\n');
  }
  if (path.includes('/summaries/')) {
    return `The mock model completed this step of "${title}". It inspected the workspace, wrote the requested files and made no other changes. This summary was generated at ${now}.\n`;
  }
  return [`# ${title}`, '', `Result for task ${task}.`, '', '| Item | Value |', '|---|---|', '| Status | done |', `| Generated | ${now} |`, ''].join('\n');
}

export function nextReply(messages: ChatMessage[], tools: ToolDef[] | undefined): ScriptedReply {
  if (!tools || tools.length === 0) {
    const last = textOf([...messages].reverse().find((m) => m.role === 'user')?.content);
    return { kind: 'text', text: last.length > 0 ? 'Agent task' : 'OK' };
  }
  const lastUserIdx = messages.map((m) => m.role).lastIndexOf('user');
  const userText = textOf(messages[lastUserIdx]?.content);
  const after = messages.slice(lastUserIdx + 1);
  const writeTool = findWriteTool(tools);
  const cwd = workingDirectory(messages);

  // Test hook: "Run the command `ls -la`" makes the model call the shell tool once.
  const command = /\brun the command\b[^`]*`([^`]+)`/i.exec(userText)?.[1];
  const shellTool = tools.find((t) => /^(bash|shell)$/i.test(t.function.name));
  if (command && shellTool && !after.some((m) => m.tool_calls?.some((c) => c.function.name === shellTool.function.name))) {
    return { kind: 'tool', name: shellTool.function.name, args: { command, description: 'requested command' } };
  }

  // Test hook: 'Call the tool `demo__fx_rate` with `{"from":"EUR","to":"USD"}`' calls each named (MCP) tool once,
  // only in EXECUTE steps (delegations are collected there; INTEGRATE must not delegate again).
  if (/Your job in this step: EXECUTE/.test(userText)) {
    for (const m of userText.matchAll(/\bcall the tool\s*`([^`]+)`(?:\s*with\s*`([^`]*)`)?/gi)) {
      const tool = tools.find((t) => t.function.name === m[1] || t.function.name.endsWith(`_${m[1]}`));
      if (!tool || after.some((x) => x.tool_calls?.some((c) => c.function.name === tool.function.name))) continue;
      let args: Record<string, unknown> = {};
      try {
        args = m[2] ? (JSON.parse(m[2]) as Record<string, unknown>) : {};
      } catch {
        /* keep empty */
      }
      return { kind: 'tool', name: tool.function.name, args };
    }
  }

  if (writeTool) {
    const written = new Set<string>();
    for (const m of after) {
      for (const call of m.tool_calls ?? []) {
        try {
          const args = JSON.parse(call.function.arguments) as Record<string, unknown>;
          const p = String(args[writeTool.pathKey] ?? '');
          written.add(p.startsWith(cwd + '/') ? p.slice(cwd.length + 1) : p);
        } catch {
          /* ignore */
        }
      }
    }
    const pending = extractWriteTargets(userText).filter((p) => !written.has(p));
    if (pending.length > 0) {
      const target = pending[0]!;
      return {
        kind: 'tool',
        name: writeTool.name,
        args: { [writeTool.pathKey]: `${cwd}/${target}`, [writeTool.contentKey]: contentFor(target, userText) },
      };
    }
  }
  const targets = extractWriteTargets(userText);
  return {
    kind: 'text',
    text: targets.length
      ? `Done. I wrote ${targets.map((t) => `\`${t}\``).join(', ')}.`
      : 'Done. No file changes were necessary for this step.',
  };
}
