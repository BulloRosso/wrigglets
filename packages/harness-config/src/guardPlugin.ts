/*
 * The opencode plugin that connects the Agent Harness to the exfiltration guard (ADR-0033).
 *
 * opencode calls the plugin hook `tool.execute.before` for EVERY tool call, before the tool runs; throwing an error
 * from the hook cancels the call and hands the message to the model as the tool's error. The plugin does nothing
 * but forward the call to the agent server on loopback (`GUARD_URL`, bearer `GUARD_TOKEN`), where the evaluation
 * agent decides. It is plain ES2022 without dependencies, because it is loaded by opencode (Bun) from a file that the
 * supervisor writes next to the harness config, outside the workspace.
 *
 * Fail closed: if the agent server cannot be reached or answers anything but an explicit `allow`, the call is refused.
 * (What happens when the *evaluation* fails is decided server-side by the guard's `failMode`.)
 */

export const GUARD_PLUGIN_FILENAME = 'exfiltration-guard.mjs';

/** Environment variables the plugin reads (set by the harness supervisor). */
export const GUARD_ENV = { url: 'GUARD_URL', token: 'GUARD_TOKEN' } as const;

export const GUARD_PLUGIN_SOURCE = `// Generated by @cw/harness-config — do not edit. Exfiltration guard (ADR-0033).
const TIMEOUT_MS = 45_000;

export const ExfiltrationGuard = async () => ({
  'tool.execute.before': async (input, output) => {
    const url = process.env.${GUARD_ENV.url};
    const token = process.env.${GUARD_ENV.token};
    if (!url || !token) throw new Error('Security guard is not configured; the tool call was refused.');
    let verdict;
    try {
      const res = await fetch(url, {
        method: 'POST',
        headers: { authorization: 'Bearer ' + token, 'content-type': 'application/json' },
        body: JSON.stringify({ sessionID: input.sessionID, callID: input.callID, tool: input.tool, args: output && output.args }),
        signal: AbortSignal.timeout(TIMEOUT_MS),
      });
      if (!res.ok) throw new Error('guard answered ' + res.status);
      verdict = await res.json();
    } catch (err) {
      throw new Error('Security guard unavailable; the tool call was refused (' + (err && err.message ? err.message : String(err)) + ').');
    }
    if (!verdict || verdict.decision !== 'allow') {
      throw new Error((verdict && verdict.message) || 'Blocked by the security guard.');
    }
  },
});
`;
