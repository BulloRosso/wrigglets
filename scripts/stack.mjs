#!/usr/bin/env node
// Local stack helper for Docker Desktop (cross-platform: Windows, macOS, Linux).
//   node scripts/stack.mjs up      create .env if missing, build all images, start the stack
//   node scripts/stack.mjs build   build all images (incl. the agent image)
//   node scripts/stack.mjs down    stop the stack (agent containers keep running unless --agents)
//   node scripts/stack.mjs reset   stop everything and delete all data volumes (asks no questions!)
import { spawnSync } from 'node:child_process';
import { randomBytes } from 'node:crypto';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const envFile = path.join(root, '.env');
const cmd = process.argv[2] ?? 'up';
const flags = new Set(process.argv.slice(3));

function run(bin, args, opts = {}) {
  console.log(`\n$ ${bin} ${args.join(' ')}`);
  const r = spawnSync(bin, args, { cwd: root, stdio: 'inherit', shell: false, ...opts });
  if (r.status !== 0 && !opts.allowFail) process.exit(r.status ?? 1);
  return r;
}

const capture = (bin, args) => spawnSync(bin, args, { cwd: root, encoding: 'utf8' }).stdout.trim();
const secret = (n = 24) => randomBytes(n).toString('base64url');
const password = () => `${secret(9)}-${Math.floor(Math.random() * 90 + 10)}`;

/** Secrets added after the first version; appended to an existing .env when missing. */
const laterSecrets = () => ({
  GATEWAY_TOKEN: secret(32),
  MCP_DEMO_TOKEN: secret(24),
  MCP_WEB_TOKEN: secret(24),
  MCP_WIKI_TOKEN: secret(24),
  WIKI_ADMIN_TOKEN: secret(24),
  // LiteLLM requires keys starting with "sk-"
  CW_LITELLM_MASTER_KEY: `sk-${secret(32)}`,
  CW_LITELLM_SALT_KEY: `sk-${secret(32)}`,
  CW_LITELLM_DB_PASSWORD: secret(24),
});

/** Settings of earlier versions that are no longer valid (the scripted mock model was removed, ADR-0029). */
const OBSOLETE = /^(AI_GATEWAY_BASE_URL|AI_GATEWAY_API_KEY|MOCK_CHUNK_DELAY_MS)=.*$|^AI_GATEWAY_MODEL=mock-.*$|^# Model provider\..*$/;

function ensureEnv() {
  if (existsSync(envFile)) {
    const original = readFileSync(envFile, 'utf8');
    const cleaned = original
      .split(/\r?\n/)
      .filter((l) => !OBSOLETE.test(l))
      .join('\n');
    if (cleaned !== original) {
      writeFileSync(envFile, cleaned);
      console.log('Removed the settings of the old mock model from .env (the AI model is now LiteLLM → OpenAI).');
    }
    const have = readEnv();
    const missing = Object.entries(laterSecrets()).filter(([k]) => !have[k]);
    if (missing.length) {
      const current = readFileSync(envFile, 'utf8');
      const added = missing.map(([k, v]) => `${k}=${v}`).join('\n');
      writeFileSync(envFile, `${current}${current.endsWith('\n') ? '' : '\n'}${added}\n`);
      console.log(`Added ${missing.map(([k]) => k).join(', ')} to ${envFile}.`);
    }
    return false;
  }
  const lines = [
    '# Generated by scripts/stack.mjs — local development secrets. Do not commit.',
    `PAYLOAD_CODEC_KEYS=k1:${randomBytes(32).toString('base64')}`,
    `OAUTH_ADMIN_TOKEN=${secret(32)}`,
    `ADMIN_CLIENT_SECRET=${secret(24)}`,
    `ADMIN_SESSION_SECRET=${secret(32)}`,
    ...Object.entries(laterSecrets()).map(([k, v]) => `${k}=${v}`),
    'BOOTSTRAP_ADMIN_EMAIL=admin@example.local',
    `BOOTSTRAP_ADMIN_PASSWORD=${password()}`,
    'SEED_DEMO_USERS=true',
    `DEMO_USER_PASSWORD=${password()}`,
    '',
    '# AI model: LiteLLM → OpenAI. OPENAI_API_KEY comes from your environment (never put it here).',
    '# Default model for new agents (must be in infra/litellm/config.yaml) and default spend limit per agent (USD / 30 days).',
    'AI_GATEWAY_MODEL=gpt-5.4-mini',
    'AI_GATEWAY_SMALL_MODEL=gpt-5.4-nano',
    'AGENT_SPEND_LIMIT_USD=25',
    '',
    'TEMPORAL_NAMESPACE=agent-dev',
    'AGENT_IMAGE=coworking/agent:local',
    '# Short approval timers are handy for demos, e.g. APPROVAL_REMINDER_AFTER=2m',
    'APPROVAL_REMINDER_AFTER=4h',
    'APPROVAL_EXPIRE_AFTER=7d',
    'LOG_LEVEL=info',
    '',
  ];
  writeFileSync(envFile, lines.join('\n'));
  console.log(`Created ${envFile} with fresh secrets.`);
  return true;
}

function readEnv() {
  return Object.fromEntries(
    readFileSync(envFile, 'utf8')
      .split(/\r?\n/)
      .filter((l) => l && !l.startsWith('#') && l.includes('='))
      .map((l) => [l.slice(0, l.indexOf('=')), l.slice(l.indexOf('=') + 1)]),
  );
}

function build() {
  ensureEnv();
  run('docker', ['compose', '--profile', 'build', 'build']);
}

function waitHealthy(url, label, timeoutMs = 180_000) {
  const deadline = Date.now() + timeoutMs;
  process.stdout.write(`Waiting for ${label} `);
  while (Date.now() < deadline) {
    const r = spawnSync(process.execPath, ['-e', `fetch(${JSON.stringify(url)}).then(r=>process.exit(r.ok?0:1)).catch(()=>process.exit(1))`]);
    if (r.status === 0) {
      console.log('✓');
      return true;
    }
    process.stdout.write('.');
    spawnSync(process.execPath, ['-e', 'setTimeout(()=>{},2000)']);
  }
  console.log('✗ (timeout)');
  return false;
}

switch (cmd) {
  case 'build':
    build();
    break;
  case 'up': {
    if (capture('docker', ['info', '--format', '{{.ServerVersion}}']) === '') {
      console.error('Docker is not running. Start Docker Desktop first.');
      process.exit(1);
    }
    if (!process.env.OPENAI_API_KEY) {
      console.warn(`
!! OPENAI_API_KEY is not set in this environment. Agents need a real AI model:
!!   Windows:  setx OPENAI_API_KEY "sk-..."   (then open a new terminal)
!!   macOS/Linux: export OPENAI_API_KEY=sk-...
!! The stack starts anyway; agents and the admin console show what is missing.
`);
    }
    build();
    run('docker', ['compose', 'up', '-d', '--remove-orphans']);
    const env = readEnv();
    const host = env.PUBLIC_HOST || 'localhost';
    const ok =
      waitHealthy(`http://${host}:9000/health`, 'OAuth server') &
      waitHealthy(`http://${host}:8080/health`, 'Temporal + admin console') &
      waitHealthy(`http://${host}:4000/health/liveliness`, 'LiteLLM (AI gateway)');
    console.log(`
────────────────────────────────────────────────────────────────────────
 Coworking Agents — local stack ${ok ? 'is up' : 'started (some services are not healthy yet)'}

  Admin console     http://${host}:8080
  Temporal Web UI   http://${host}:8233
  OAuth server      http://${host}:9000

  LiteLLM           http://${host}:4000/ui   (user admin, password = CW_LITELLM_MASTER_KEY in .env)

  AI model          ${process.env.OPENAI_API_KEY ? `OpenAI via LiteLLM, default ${env.AI_GATEWAY_MODEL || 'gpt-5.4-mini'} (OPENAI_API_KEY from your environment)` : 'NOT CONFIGURED — set OPENAI_API_KEY in your environment and run this again'}
  Agent portraits   ${process.env.OPENAI_API_KEY ? 'enabled' : 'disabled (needs OPENAI_API_KEY)'}

  Platform admin    ${env.BOOTSTRAP_ADMIN_EMAIL}  /  ${env.BOOTSTRAP_ADMIN_PASSWORD}
  Demo users        anna@example.com, ben@example.com (approver), clara@example.com
                    password: ${env.DEMO_USER_PASSWORD}   (seeded on first start only)

 Next: sign in to the admin console → Agents → "New agent".
────────────────────────────────────────────────────────────────────────`);
    break;
  }
  case 'down': {
    run('docker', ['compose', 'down']);
    if (flags.has('--agents')) {
      const ids = capture('docker', ['ps', '-aq', '--filter', 'label=cw.role=agent']).split(/\s+/).filter(Boolean);
      if (ids.length) run('docker', ['rm', '-f', ...ids]);
    }
    break;
  }
  case 'reset': {
    const ids = capture('docker', ['ps', '-aq', '--filter', 'label=cw.role=agent']).split(/\s+/).filter(Boolean);
    if (ids.length) run('docker', ['rm', '-f', ...ids]);
    const vols = capture('docker', ['volume', 'ls', '-q', '--filter', 'label=cw.role=agent-home']).split(/\s+/).filter(Boolean);
    if (vols.length) run('docker', ['volume', 'rm', ...vols]);
    run('docker', ['compose', 'down', '-v']);
    if (flags.has('--env') && existsSync(envFile)) {
      writeFileSync(envFile + '.bak', readFileSync(envFile));
      spawnSync(process.execPath, ['-e', `require('fs').unlinkSync(${JSON.stringify(envFile)})`]);
      console.log('Removed .env (backup in .env.bak).');
    }
    break;
  }
  case 'env':
    // create or migrate .env only (new secrets, removal of obsolete settings)
    ensureEnv();
    break;
  default:
    console.error(`Unknown command "${cmd}". Use up | build | env | down [--agents] | reset [--env].`);
    process.exit(1);
}
